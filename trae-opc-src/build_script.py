for s in doc.sections:
    s.left_margin = s.right_margin = Cm(2.2); s.top_margin = s.bottom_margin = Cm(2)

def para(text, size=13, bold=False, color=None, space_after=6, indent=False):
    p = doc.add_paragraph()
    r = p.add_run(text); r.font.size = Pt(size); r.bold = bold
    r.font.name = "微软雅黑"; r._element.rPr.rFonts.set(qn("w:eastAsia"), "微软雅黑")
    if color: r.font.color.rgb = RGBColor(*color)
    p.paragraph_format.space_after = Pt(space_after); p.paragraph_format.line_spacing = 1.45
    if indent: p.paragraph_format.left_indent = Cm(0.4)
    return p

